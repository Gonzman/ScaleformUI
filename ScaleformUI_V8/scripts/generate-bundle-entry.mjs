import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDir, "..");
const srcDir = path.join(projectRoot, "src");
const generatedDir = path.join(srcDir, "__generated__");
const outputFile = path.join(generatedDir, "bundle-entry.ts");

const excluded = (relativePath) => {
  const normalized = relativePath.split(path.sep).join("/");
  return (
    normalized === "index.ts" ||
    normalized.endsWith(".d.ts") ||
    normalized.endsWith(".test.ts") ||
    normalized.startsWith("examples/") ||
    normalized.startsWith("__generated__/")
  );
};

const walk = async (dir) => {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const nested = await Promise.all(
    entries.map(async (entry) => {
      const fullPath = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        return walk(fullPath);
      }

      if (!entry.isFile() || !entry.name.endsWith(".ts")) {
        return [];
      }

      const relativePath = path.relative(srcDir, fullPath);
      return excluded(relativePath) ? [] : [relativePath];
    })
  );

  return nested.flat();
};

const toImportSpecifier = (relativePath) => {
  const absoluteSourcePath = path.join(srcDir, relativePath);
  const relativeFromGenerated = path.relative(generatedDir, absoluteSourcePath);
  const normalized = relativeFromGenerated
    .split(path.sep)
    .join("/")
    .replace(/\.ts$/, "");

  return normalized.startsWith(".") ? normalized : `./${normalized}`;
};

const files = (await walk(srcDir)).sort((a, b) => a.localeCompare(b));
if (files.length === 0) {
  throw new Error("No source files found for bundle entry generation.");
}

const imports = files.map((file) => `import "${toImportSpecifier(file)}";`).join("\n");
const content =
  "// AUTO-GENERATED FILE. DO NOT EDIT.\n" +
  "// Generated by scripts/generate-bundle-entry.mjs\n" +
  `${imports}\n`;

await fs.mkdir(generatedDir, { recursive: true });
await fs.writeFile(outputFile, content, "utf8");

process.stdout.write(
  `Generated ${path.relative(projectRoot, outputFile)} with ${files.length} imports.\n`
);
